<?php

declare(strict_types=1);

namespace JmaXml\Codegen;

use FilesystemIterator;
use JmaXml\Codegen\Dictionary\Dictionary;
use JmaXml\Codegen\Php\ClassRenderer;
use JmaXml\Codegen\Php\Naming;
use JmaXml\Codegen\Schema\SchemaSet;
use LogicException;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use RuntimeException;
use SplFileInfo;

/**
 * Generates the typed model classes of jmaxml/core from the JMA XML schema and dictionary.
 *
 * @author shimomo
 */
final class Generator
{
    public const string MARKER = '// This file is generated by tools/codegen. Do not edit it by hand.';

    private readonly ClassRenderer $renderer;

    /**
     * @param array<string, string> $namespaceMap XML namespace URI => PHP namespace
     * @param string $baseNamespace PHP namespace that maps to the output directory
     */
    public function __construct(
        private readonly SchemaSet $schemas,
        Dictionary $dictionary,
        array $namespaceMap,
        private readonly string $baseNamespace = 'JmaXml',
    ) {
        $this->renderer = new ClassRenderer($schemas, $dictionary, $namespaceMap);
    }

    /**
     * @return array<string, string>
     */
    public static function defaultNamespaceMap(): array
    {
        return [
            'http://xml.kishou.go.jp/jmaxml1/' => 'JmaXml',
            'http://xml.kishou.go.jp/jmaxml1/informationBasis1/' => 'JmaXml\\InformationBasis',
            'http://xml.kishou.go.jp/jmaxml1/elementBasis1/' => 'JmaXml\\ElementBasis',
            'http://xml.kishou.go.jp/jmaxml1/body/meteorology1/' => 'JmaXml\\Meteorology',
            'http://xml.kishou.go.jp/jmaxml1/body/seismology1/' => 'JmaXml\\Seismology',
            'http://xml.kishou.go.jp/jmaxml1/body/volcanology1/' => 'JmaXml\\Volcanology',
        ];
    }

    /**
     * @return array<string, string> path relative to the output directory => file contents, sorted by path
     */
    public function generate(): array
    {
        $files = [];

        foreach ($this->schemas->complexTypes() as $type) {
            $path = $this->directoryFor($this->renderer->phpNamespace($type->namespace)) . Naming::className($type->name) . '.php';

            if (isset($files[$path])) {
                throw new LogicException('Two types would be written to ' . $path);
            }

            $files[$path] = $this->renderer->render($type);
        }

        ksort($files, SORT_STRING);

        return $files;
    }

    /**
     * Writes the generated files and removes generated files that are no longer produced.
     *
     * @return list<string> written paths relative to $outputDir
     */
    public function writeTo(string $outputDir): array
    {
        $files = $this->generate();

        foreach ($files as $path => $contents) {
            $target = $outputDir . '/' . $path;

            if (!is_dir(dirname($target)) && !mkdir(dirname($target), 0777, true) && !is_dir(dirname($target))) {
                throw new RuntimeException('Cannot create directory ' . dirname($target));
            }

            if (file_put_contents($target, $contents) === false) {
                throw new RuntimeException('Cannot write ' . $target);
            }
        }

        $entries = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($outputDir, FilesystemIterator::SKIP_DOTS));

        /** @var SplFileInfo $entry */
        foreach ($entries as $entry) {
            $relative = substr($entry->getPathname(), strlen($outputDir) + 1);

            if ($entry->getExtension() !== 'php' || isset($files[$relative])) {
                continue;
            }

            $contents = file_get_contents($entry->getPathname());

            if ($contents !== false && str_contains($contents, self::MARKER)) {
                unlink($entry->getPathname());
            }
        }

        return array_keys($files);
    }

    private function directoryFor(string $phpNamespace): string
    {
        if ($phpNamespace === $this->baseNamespace) {
            return '';
        }

        if (!str_starts_with($phpNamespace, $this->baseNamespace . '\\')) {
            throw new LogicException($phpNamespace . ' is outside the base namespace ' . $this->baseNamespace);
        }

        return str_replace('\\', '/', substr($phpNamespace, strlen($this->baseNamespace) + 1)) . '/';
    }
}
